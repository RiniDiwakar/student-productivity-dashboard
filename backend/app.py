
import os

from flask import Flask, request, jsonify
from flask_cors import CORS
import psycopg
from psycopg.rows import dict_row

app = Flask(__name__)
CORS(app)

DATABASE_URL = os.environ.get("DATABASE_URL")


# Connect to Neon PostgreSQL
def get_db_connection():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL environment variable is not configured."
        )

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=10,
        sslmode="require"
    )


# Create database tables
def initialize_database():
    with get_db_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS tasks (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                text TEXT NOT NULL,
                priority TEXT NOT NULL,
                completed INTEGER NOT NULL DEFAULT 0
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS assignments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                subject TEXT NOT NULL,
                deadline TEXT NOT NULL
            )
        """)


# Home route
@app.route("/")
def home():
    return jsonify({
        "message": "Student Productivity Dashboard API is running!"
    })


# Get all tasks
@app.route("/api/tasks", methods=["GET"])
def get_tasks():
    with get_db_connection() as connection:
        rows = connection.execute(
            "SELECT * FROM tasks ORDER BY id DESC"
        ).fetchall()

    return jsonify([dict(row) for row in rows])


# Add a task
@app.route("/api/tasks", methods=["POST"])
def add_task():
    data = request.get_json(silent=True) or {}

    text = data.get("text", "").strip()
    priority = data.get("priority", "Medium")

    if not text:
        return jsonify({"error": "Task text is required"}), 400

    if priority not in ("Low", "Medium", "High"):
        return jsonify({"error": "Invalid priority"}), 400

    with get_db_connection() as connection:
        row = connection.execute(
            """
            INSERT INTO tasks (text, priority)
            VALUES (%s, %s)
            RETURNING id
            """,
            (text, priority)
        ).fetchone()

    return jsonify({
        "id": row["id"],
        "text": text,
        "priority": priority,
        "completed": 0
    }), 201


# Mark a task complete or incomplete
@app.route("/api/tasks/<int:task_id>", methods=["PATCH"])
def update_task(task_id):
    data = request.get_json(silent=True) or {}

    if "completed" not in data:
        return jsonify({"error": "Completed status is required"}), 400

    completed = data["completed"]

    if completed not in (True, False, 0, 1):
        return jsonify({"error": "Invalid completed status"}), 400

    with get_db_connection() as connection:
        cursor = connection.execute(
            "UPDATE tasks SET completed = %s WHERE id = %s",
            (int(completed), task_id)
        )

        if cursor.rowcount == 0:
            return jsonify({"error": "Task not found"}), 404

    return jsonify({"message": "Task updated successfully"})


# Delete a task
@app.route("/api/tasks/<int:task_id>", methods=["DELETE"])
def delete_task(task_id):
    with get_db_connection() as connection:
        cursor = connection.execute(
            "DELETE FROM tasks WHERE id = %s",
            (task_id,)
        )

        if cursor.rowcount == 0:
            return jsonify({"error": "Task not found"}), 404

    return jsonify({"message": "Task deleted successfully"})


